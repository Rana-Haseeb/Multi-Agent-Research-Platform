def agent_specifications() -> str:
    L = [STAMP, "", "# Agent Specifications (§26)", "",
         "Six specialised agents. Each entry states what the agent may do, what it may not, and "
         "**which of those limits is enforced by code rather than by prompt wording** — that "
         "distinction is the difference between a guarantee and a request.", "",
         "Tools and permissions are read from the live registry, so this cannot drift from what "
         "actually runs.", "",
         "Two identities in `AgentId` are deliberately **not** specified here because they are not "
         "workflow agents: `SYSTEM` is the pseudo-identity used by deterministic nodes and holds no "
         "tool grants at all (asserted by "
         "`test_a11_a_non_agent_identity_cannot_call_tools`), and `BASELINE` is Experiment 1's "
         "single-agent control arm, which exists to be compared against this design rather than to "
         "be part of it.", ""]
    for agent, spec in AGENT_SPEC.items():
        tools = sorted(s.name for s in tools_for(agent))
        L += [f"## {agent.value}", "",
              f"**Purpose.** {spec['purpose']}", "",
              "**Responsibilities**", ""]
        L += [f"- {r}" for r in spec["responsibilities"]]
        L += ["", f"**Inputs.** {spec['inputs']}", "",
              f"**Outputs.** {spec['outputs']}", "",
              f"**Tools ({len(tools)}).** " + (", ".join(f"`{t}`" for t in tools) or "none"), "",
              "**Prohibited actions**", ""]
        L += [f"- {p}" for p in spec["prohibited"]]
        L += ["", f"**Handoff.** {spec['handoff']}", "",
              f"**Failure behaviour.** {spec['failure']}", "",
              f"**Prompt strategy.** {spec['prompt']}", ""]
    L += ["## Permission matrix", "", permission_matrix(), "",
          "Enforced in `run_tool()` *before* the tool function is reached and before argument "
          "validation, so a forbidden call fails as forbidden even when its arguments are also "
          "malformed. Every refused call is logged with `outcome: permission_denied`.", ""]
    return "\n".join(L)


