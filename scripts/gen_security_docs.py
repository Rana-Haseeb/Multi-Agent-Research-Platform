# §31 Adversarial results — parsed from the test suite
# --------------------------------------------------------------------------- #
def adversarial_results() -> tuple[str, int]:
    src = (ROOT / "tests" / "test_adversarial.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    rows = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef) or not node.name.startswith("test_"):
            continue
        doc = ast.get_docstring(node) or ""
        # The ATTACK clause must stop at DEFENCE even when both share one line, otherwise the
        # defence text bleeds into the attack column (a9 did exactly that).
        attack = re.search(r"ATTACK:\s*(.+?)(?:\n\n|\s*DEFENCE|\Z)", doc, re.S)
        defence = re.search(r"DEFENCE(?:\s*\(([^)]+)\))?:\s*(.+?)(?:\n\n|\Z)", doc, re.S)
        summary = doc.strip().split("\n")[0] if doc else node.name
        rows.append({
            # "test_a5b_..." belongs to scenario a5, and inherits its attack.
            "scenario": re.match(r"test_([a-z]+\d+)", node.name).group(1)
                        if re.match(r"test_([a-z]+\d+)", node.name) else node.name,
            "test": node.name,
            "attack": " ".join(attack.group(1).split()) if attack else "",
            "kind": (defence.group(1) if defence and defence.group(1) else ""),
            "defence": " ".join(defence.group(2).split()) if defence else
                       " ".join(summary.split()),
        })

    # Sub-tests (a5b, a5c) state only their own defence; the attack is the scenario's.
    for r in rows:
        if not r["attack"]:
            parent = next((p for p in rows if p["scenario"] == r["scenario"] and p["attack"]), None)
            r["attack"] = f"{parent['attack']} *(same scenario)*" if parent else "—"

    result = subprocess.run([sys.executable, "-m", "pytest", "tests/test_adversarial.py",
                             "-q", "--no-header"], cwd=ROOT, capture_output=True, text=True)
    tail = [ln for ln in result.stdout.strip().splitlines() if ln.strip()][-1:] or [""]

    L = [STAMP, "", "# Adversarial Test Results (§31)", "",
         f"**{len(rows)} adversarial tests, all passing** — `{tail[0]}`", "",
         "§31 asks for ten difficult tests and for documentation of how the system responds. "
         "Every row below is an assertion that runs in CI, not a description of intended "
         "behaviour. \"It didn't throw\" is not counted as a defence.", "",
         "Where a defence is marked **structural**, it is enforced by a permission check, a "
         "schema validator or a comparison in the router — it holds regardless of what any "
         "model was persuaded to emit. Where it is **instructional**, it is prompt wording and "
         "is therefore the last line of defence, never the only one. A row with no kind asserts "
         "that an attack is *reachable* rather than asserting a defence — a defence whose attack "
         "cannot be reproduced is untested.", "",
         "| # | Attack | Defence | Kind | Test |", "|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        kind = "**structural**" if "structural" in r["kind"] else (
            "instructional" if "instructional" in r["kind"] else "—")
        # No truncation: a defence cut off mid-sentence documents nothing.
        cell = lambda s: s.replace("|", "\\|")
        L.append(f"| {i} | {cell(r['attack'])} | {cell(r['defence'])} | {kind} | `{r['test']}` |")
    L += ["", "## Coverage against §31's listed scenarios", "",
          "| §31 scenario | Covered by |", "|---|---|",
          "| Conflicting sources | A1 — both sides of planted defect PD1 retrievable together |",
          "| Missing information | A2 — empty search returns zero hits with guidance |",
          "| Unsupported certainty | A3 — schema rejects uncited major claims |",
          "| No useful evidence | A2b — handoff must declare a gap |",
          "| Invalid agent output | A4 — cyclic plan fails cleanly, no deadlock |",
          "| Critic rejects repeatedly | A5 — terminates at the cap, objections in the report |",
          "| Search tool fails | A6 — error fed back to the agent, corpus outage handled |",
          "| Prompt injection | A7 — corpus payload plus request-level guard |",
          "| Duplicate research task | A8 — collapsed deterministically, dependents rewired |",
          "| User changes objective | A10 — plan rejection aborts before research |",
          "| Runaway loops / cost | A9 — every loop has a finite, tested cap |",
          "| Agent impersonation | A11 — SYSTEM identity cannot call tools |", ""]
    return "\n".join(L), len(rows)


