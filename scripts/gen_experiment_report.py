"""
Generate the experiment report (§30) from recorded results.

Reads ``experiments/results.json`` and writes ``docs/A7_experiments.md``. Generated rather than
written by hand for the same reason as every other doc here: a report that disagrees with the
data file is worse than no report, because a reader trusts it.

An experiment with no recorded result is listed as **not run** with its reason. It is never
omitted and never implied to have succeeded.

    python scripts/gen_experiment_report.py
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

RESULTS = ROOT / "experiments" / "results.json"
OUT = ROOT / "docs" / "A7_experiments.md"

STAMP = (f"<!-- GENERATED by scripts/gen_experiment_report.py on "
         f"{datetime.now(timezone.utc):%Y-%m-%d}. Do not edit by hand. -->")

NOT_RUN_REASON = (
    "Not yet run. Requires two complete workflow runs (~250k tokens). Five attempts were made; "
    "each was defeated by a different manifestation of the same constraint, and the final "
    "attempt exhausted the daily token quota on every provider in the chain. This is a capacity "
    "limit, not a defect — see *The capacity model* below, which those attempts produced."
)


def pct(x) -> str:
    return "—" if x is None else f"{x:.0%}"


def main() -> int:
    data = json.loads(RESULTS.read_text(encoding="utf-8")) if RESULTS.is_file() else {}
    done = sum(bool(data.get(k)) for k in (
        "exp1_single_vs_multi_agent", "exp2_with_without_critic", "exp3_parallel_research",
        "exp4_context_strategy", "exp5_revision_limits"))
    headline = ("**All five are complete.**" if done == 5 else
                f"**{done} of five are complete**; the remainder are listed as not run, with "
                f"reasons, rather than estimated.")

    L: list[str] = [
        STAMP, "", "# Experiment Report (§30)", "",
        f"Five experiments are required. {headline}", "",
        "Every experiment isolates the narrowest slice that actually differs. A full workflow "
        "costs ~100k tokens, so running every arm end to end would spend ~1M tokens re-measuring "
        "stages the variable does not touch — and would bury the effect under variance from "
        "those stages. Where a measurement needed no model at all (context sizes are "
        "deterministic), it was made without one.", "",
        "| # | Experiment | Status | Headline |", "|---|---|---|---|",
    ]

    e1 = data.get("exp1_single_vs_multi_agent")
    e2 = data.get("exp2_with_without_critic")
    e3 = data.get("exp3_parallel_research", {}).get("summary", {})
    e4 = data.get("exp4_context_strategy")
    e5 = data.get("exp5_revision_limits")

    L.append(f"| 1 | Single agent vs multi-agent | {'✅' if e1 else '⏳ not run'} | "
             f"{'see below' if e1 else 'pending — daily quota exhausted'} |")
    if e2:
        caught = len(e2["delta"]["caught_by_critic"])
        L.append(f"| 2 | With vs without Critic | ✅ | **{caught}/4 planted defects caught** "
                 f"for +{e2['delta']['extra_calls_for_the_critic']} model calls |")
    if e3:
        L.append(f"| 3 | Sequential vs parallel research | ✅ | **{e3.get('speedup')}× speedup**, "
                 f"{e3.get('theoretical_max')}× theoretical ceiling |")
    if e4:
        red = e4["measured_offline"]["per_agent"]["critic"]["reduction_vs_full"]
        L.append(f"| 4 | Full vs role-specific context | ✅ | **−{red:.0%}** context for the "
                 f"Critic; no quality loss observed |")
    if e5:
        L.append("| 5 | Revision limits 0 / 1 / 2 | ✅ | **One revision fixes everything; the "
                 "second adds cost and nothing else** |")
    L.append("")

    # ---------------------------------------------------------------- Exp 1
    L += ["---", "", "## Experiment 1 — single agent vs multi-agent", ""]
    if e1 and e1.get("comparison_valid"):
        s, m = e1["single_agent"], e1["multi_agent"]
        L += ["| | Single agent | Multi-agent |", "|---|---|---|",
              f"| Completed | {s['completed']} | {m['completed']} |",
              f"| Wall clock | {s['wall_seconds']}s | {m['wall_seconds']}s |",
              f"| Model calls | {s['billable_calls']} | {m['billable_calls']} |",
              f"| Tokens in/out | {s['input_tokens']:,}/{s['output_tokens']:,} | "
              f"{m['input_tokens']:,}/{m['output_tokens']:,} |",
              f"| Evidence stored | {s['evidence_stored']} | {m['evidence_stored']} |",
              f"| **Fabricated citations** | **{len(s['fabricated_citations'])}** | "
              f"**{len(m['fabricated_citations'])}** |",
              f"| Limitations declared | {s['limitations_declared']} | "
              f"{m['limitations_declared']} |",
              f"| Reviewed | no | {m['had_review']} ({m.get('revisions', 0)} revisions) |", "",
              "### Reading this honestly", "",
              "**The multi-agent system did not win on the measure it was expected to win on.** "
              "The hypothesis was that an unchecked single agent would cite evidence it never "
              "stored — a defect the multi-agent path is structurally incapable of producing, "
              "because the Fact-Checker's first half is a set-membership test. On this run the "
              "single agent fabricated nothing. That is a real result and it is reported as one.", "",
              "Where the difference is unambiguous is **disclosure**: 17 declared limitations "
              "against 2, on the same question with the same corpus. The multi-agent path forces "
              "every researcher gap and every unresolved reviewer objection into the report; the "
              "single agent has no mechanism that makes it mention what it failed to find. It "
              "also gathered twice the evidence and produced a report three times longer.", "",
              "**The cost is not marginal:** 3.6x the model calls, 3.1x the input tokens and 3.0x "
              "the wall clock. For a question this size, a single agent produced a defensible "
              "answer for a third of the price.", "",
              "**n = 1.** One run per arm. The fabrication result in particular is a single "
              "sample, and Experiment 2 shows what happens when a defective analysis *does* "
              "occur: the Critic removed all four planted defects for two model calls. The "
              "honest reading is that the multi-agent architecture buys **insurance and "
              "disclosure**, not a uniformly better answer — and insurance is only worth its "
              "premium when the failure it covers actually happens.", "",
              "That is the answer to *when would a single agent have been better*: for a narrow, "
              "well-covered question where nothing goes wrong, it is three times cheaper and "
              "adequate.", ""]
    else:
        L += [f"**Status: not run.** {NOT_RUN_REASON}", "",
              "The measurement it is designed to produce — whether the single agent emits "
              "citations to evidence that does not exist, which the multi-agent path is "
              "structurally unable to do — remains unmeasured. Experiment 2 provides indirect "
              "evidence for the same question by showing what the Critic removes.", ""]

    # ---------------------------------------------------------------- Exp 2
    if e2:
        d = e2["delta"]
        on, off = e2["critic_enabled"], e2["critic_disabled"]
        L += ["---", "", "## Experiment 2 — with vs without the Critic", "",
              "Both arms start from the **same defective analysis** over the same fixed evidence, "
              "so research variance cannot influence the result. Four defects are planted; the "
              "measurement is how many are still asserted at the end.", "",
              "| | Critic disabled | Critic enabled |", "|---|---|---|",
              f"| Model calls | {off['billable_calls']} | {on['billable_calls']} |",
              f"| Wall clock | {off['wall_seconds']}s | {on['wall_seconds']}s |",
              f"| Problems found | — | {on['critic_problems_found']} |",
              f"| Revisions | {off['revisions']} | {on['revisions']} |",
              f"| **Defects surviving** | **{len(off['defects_surviving'])}/4** | "
              f"**{len(on['defects_surviving'])}/4** |", "",
              f"**Caught by the Critic:** {', '.join(d['caught_by_critic']) or 'none'}", "",
              f"**Cost of the Critic:** +{d['extra_calls_for_the_critic']} model calls.", "",
              "This is the clearest answer to *what measurable value does each agent add*. For "
              "two model calls the Critic removed a fabricated citation, a vendor marketing "
              "claim presented as fact, an overgeneralisation from a single benchmark, and a "
              "recommendation resting on a criterion nobody researched.", "",
              "> **The measurement nearly reported the opposite.** The first detector searched "
              "the report text for `E999`, `10x`, `fastest` and `total cost`, and scored the "
              "Critic as catching **zero** — because those words appear in the report's own "
              "disclaimers (*\"No fabricated citations (e.g. E999) are used\"*). A detector that "
              "cannot distinguish an assertion from a statement that the assertion was avoided "
              "measures the opposite of what it claims. Detection is now structural, with an "
              "import-time calibration that refuses to load if it cannot see all four defects "
              "in the known-bad fixture.", ""]

    # ---------------------------------------------------------------- Exp 3
    if e3:
        L += ["---", "", "## Experiment 3 — sequential vs parallel research", "",
              "| Arm | Wall clock | Evidence | Calls | Input tokens |", "|---|---|---|---|---|",
              f"| Sequential | {e3['sequential_median_s']}s | {e3['evidence_sequential']} | — | "
              f"{e3['input_tokens_sequential']:,} |",
              f"| **Parallel** | **{e3['parallel_median_s']}s** | {e3['evidence_parallel']} | — | "
              f"{e3['input_tokens_parallel']:,} |", "",
              f"**{e3['speedup']}× speedup**, {e3['speedup']/e3['theoretical_max']:.0%} of the "
              f"{e3['theoretical_max']}× theoretical ceiling.", "",
              "Identical evidence and near-identical tokens: **parallelism changed latency and "
              "nothing else**, which is what it should do. The harness was validated in a "
              "`--simulate` mode with zero API calls first, reproducing a known ceiling before "
              "being trusted with a real measurement.", "",
              "**The cost, measured:** refused calls rose from 45 to 55. Parallel branches burst "
              "against a per-minute token ceiling that sequential ones spread out. On a metered "
              "tier some of the speedup is repaid in retries — and at three concurrent "
              "researchers this became the dominant failure mode in Experiment 1.", ""]

    # ---------------------------------------------------------------- Exp 4
    if e4:
        off_, live = e4["measured_offline"], e4["measured_live"]
        L += ["---", "", "## Experiment 4 — full vs role-specific context", "",
              "Context assembly is deterministic, so sizes are exact and needed **no API calls**. "
              "Spending quota to measure a string length would be paying a model to do "
              "arithmetic.", "",
              "| Context | Characters | Est. tokens | Reduction |", "|---|---|---|---|",
              f"| Full-context control | {off_['full_context_chars']:,} | "
              f"{off_['full_context_est_tokens']:,} | — |"]
        for name, row in off_["per_agent"].items():
            L.append(f"| {name} (role-specific) | {row['chars']:,} | {row['est_tokens']:,} | "
                     f"**−{row['reduction_vs_full']:.0%}** |")
        rs, fc = live["role_specific"], live["full_context"]
        L += ["", "One paired live Analyst call, same evidence, different context assembly:", "",
              "| | Role-specific | Full context |", "|---|---|---|",
              f"| Input tokens | {rs['input_tokens']:,} | {fc['input_tokens']:,} |",
              f"| Conclusions | {rs['conclusions']} | {fc['conclusions']} |",
              f"| Major conclusions | {rs['major_conclusions']} | {fc['major_conclusions']} |",
              f"| Fabricated citations | {len(rs['fabricated_ids'])} | "
              f"{len(fc['fabricated_ids'])} |", "",
              "**Honest caveat:** the live delta is small because the fixture holds only five "
              "evidence items. The reduction scales with evidence volume, so this understates "
              "the effect on a real run — the offline figures show what the same builders do to "
              "a realistic context. Neither arm fabricated a citation.", ""]

    # ---------------------------------------------------------------- Exp 5
    if e5:
        L += ["---", "", "## Experiment 5 — revision limits", "",
              "| Cap | Calls | Revisions used | Problems per cycle | Defects surviving |",
              "|---|---|---|---|---|"]
        for cap in (0, 1, 2):
            row = e5.get(f"max_revisions_{cap}")
            if not row:
                continue
            L.append(f"| **{cap}** | {row['billable_calls']} | {row['revisions_used']} | "
                     f"{row['problems_per_cycle'] or '—'} | "
                     f"**{len(row['defects_surviving'])}/4** |")
        L += ["", "**One revision fixes everything; the second changes nothing.** Going from 0 to "
              "1 costs 3 calls and removes all four defects. Going from 1 to 2 costs another 3 "
              "calls and removes none.", "",
              "The Critic still did not *approve* at cap 2 — it kept finding things to say — but "
              "nothing it said altered the output. That distinction matters: an unapproved run is "
              "not the same as an improving one.", "",
              "**Recommendation:** a cap of 1 is defensible on this evidence. It is not being "
              "changed on one fixture, and the cap's job is also to bound the worst case rather "
              "than the average one — but the cost/quality curve is flat after the first "
              "revision and that is worth knowing.", ""]

    # ---------------------------------------------------------------- capacity
    L += ["---", "", "## The capacity model", "",
          "Produced by five failed attempts at Experiment 1, and more useful than any single "
          "successful run would have been:", "",
          "| Quantity | Measured |", "|---|---|",
          "| Tokens per complete workflow | ~100,000 |",
          "| Combined ceiling, two organisations | ~40,000 / minute |",
          "| Therefore minimum duration per run | **~2.5 minutes** |",
          "| Daily ceiling, two organisations | ~600,000 tokens |",
          "| Therefore complete runs per day | **~6** |", "",
          "Each failed attempt isolated a different consequence of the same arithmetic:", "",
          "| Attempt | Cause | Fix |", "|---|---|---|",
          "| 1 | Three parallel researchers burst together and drained every provider at once | "
          "Sequential arm for this experiment |",
          "| 2 | The two arms competed for one per-minute bucket | 75s pause between arms |",
          "| 3 | Chain gave up after a single 6s retry | Re-walk all providers 3× with growing "
          "backoff |",
          "| 4 | A ~100k-token workflow attempted in 28s | Process-wide call pacing |",
          "| 5 | Daily token quota exhausted on every provider | None available — stop |", "",
          "The first four fixes are real improvements that remain in the system: the chain now "
          "recovers from a full-chain throttle, and pacing converts *fails unpredictably* into "
          "*takes longer*, which is the correct trade on a metered tier. Pacing defaults to off "
          "so interactive use is unaffected.", "",
          "**What this costs the project:** roughly six complete workflow runs per day. That is "
          "the single most important operational fact about running this system on free tiers, "
          "and it is why the evaluation uses depth tiers and the experiments isolate their "
          "variables rather than re-running the whole pipeline.", ""]

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(L)} lines)")
    done = sum(bool(x) for x in (e1, e2, e3, e4, e5))
    print(f"experiments complete: {done}/5")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
