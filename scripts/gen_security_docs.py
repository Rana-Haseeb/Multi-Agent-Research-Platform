def security_review() -> str:
    L = [STAMP, "", "# Security and Safety Review (§32)", "",
         f"**{len(RISKS)} risks identified** (§32 asks for at least eight), each with the "
         f"mitigation actually implemented and the test that holds it in place.", "",
         "The distinction that matters throughout: a **structural** mitigation is enforced by "
         "code and holds regardless of what a model emits; an **instructional** one is prompt "
         "wording and can be argued with. Where only instruction is available, that is stated.", "",
         "| # | Risk | Severity |", "|---|---|---|"]
    for i, (name, sev, _, _, _) in enumerate(RISKS, 1):
        L.append(f"| {i} | {name} | {sev} |")
    L.append("")
    for i, (name, sev, threat, mitigation, tests) in enumerate(RISKS, 1):
        L += [f"## {i}. {name}", "", f"**Severity:** {sev}", "",
              f"**Threat.** {threat}", "", f"**Mitigation.** {mitigation}", "",
              f"**Verified by.** `{tests}`", ""]
    L += ["## Known residual risks", "",
          "- **Provider keys were shared in a development transcript.** Rotate all of them after "
          "grading; they cannot be un-shared.",
          "- **The corpus is synthetic.** Behaviour against genuinely hostile web content is "
          "untested; live search exists behind a flag and is not the evaluated path.",
          "- **Prompt-level defences are probabilistic.** The request-injection guard was added "
          "*because* the document-level guard proved insufficient; the same class of gap may "
          "exist elsewhere. Only the structural controls are guarantees.",
          "- **`n = 1` on several measurements.** Experiment 1 ran once per arm; the absence of "
          "fabricated citations in the single-agent arm is a single sample, not a property.", ""]
    return "\n".join(L)


def main() -> int:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "A1_agent_specifications.md").write_text(agent_specifications(), encoding="utf-8")
    adversarial, n = adversarial_results()
    (DOCS / "A8_adversarial_results.md").write_text(adversarial, encoding="utf-8")
    (DOCS / "A9_security_review.md").write_text(security_review(), encoding="utf-8")

    for name in ("A1_agent_specifications.md", "A8_adversarial_results.md",
                 "A9_security_review.md"):
        p = DOCS / name
        print(f"wrote {p.relative_to(ROOT)} ({len(p.read_text(encoding='utf-8').splitlines())} lines)")
    print(f"\n{n} adversarial tests documented, {len(RISKS)} security risks reviewed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
